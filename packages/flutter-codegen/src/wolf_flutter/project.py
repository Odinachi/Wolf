@dataclass
class GeneratedProject:
    files: dict[str, str]
    warnings: list[str] = field(default_factory=list)


@dataclass
class ScreenInfo:
    id: str
    name: str
    class_name: str
    file_name: str
    route: str


def _package_name(schema: dict) -> str:
    bundle = (schema.get("build") or {}).get("bundleId") or ""
    last = bundle.split(".")[-1] if bundle else ""
    name = dart.snake(last or schema.get("name") or "wolf_app", "app")
    return name


def _screens(schema: dict) -> list[ScreenInfo]:
    out: list[ScreenInfo] = []
    used_classes: set[str] = set()
    used_routes: set[str] = set()
    for s in schema.get("screens") or []:
        base = dart.pascal(s.get("name") or "Screen", "Screen")
        cls = base if base.endswith("Screen") else base + "Screen"
        n = 2
        while cls in used_classes:
            cls = f"{base}{n}Screen"
            n += 1
        used_classes.add(cls)
        route_base = "/" + re.sub(r"[^a-z0-9]+", "-", (s.get("name") or "screen").lower()).strip("-")
        route, n = route_base or "/screen", 2
        while route in used_routes:
            route = f"{route_base}-{n}"
            n += 1
        used_routes.add(route)
        out.append(ScreenInfo(id=s["id"], name=s.get("name") or cls, class_name=cls, file_name=dart.snake(cls), route=route))
    return out


