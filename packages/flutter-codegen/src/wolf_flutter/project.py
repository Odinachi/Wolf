DART_TYPES = {"string": "String", "image": "String", "reference": "String", "int": "int", "double": "double", "bool": "bool", "datetime": "DateTime"}


def _from_json(field_type: str, expr: str, required: bool) -> str:
    if field_type == "double":
        return f"({expr} as num).toDouble()" if required else f"({expr} as num?)?.toDouble()"
    if field_type == "datetime":
        return f"DateTime.parse({expr} as String)" if required else f"{expr} == null ? null : DateTime.parse({expr} as String)"
    t = DART_TYPES.get(field_type, "String")
    return f"{expr} as {t}" if required else f"{expr} as {t}?"


def _to_json(field_type: str, expr: str, required: bool) -> str:
    if field_type == "datetime":
        return f"{expr}.toIso8601String()" if required else f"{expr}?.toIso8601String()"
    return expr


def _model_file(model: dict) -> tuple[str, str, str]:
    """Returns (class name, file stem, source)."""
    cls = dart.pascal(model.get("name") or "Model", "Model")
    fields = []
    used: set[str] = set()
    for f in model.get("fields") or []:
        name = dart.camel(f.get("name") or "field")
        while name in used:
            name += "_"
        used.add(name)
        fields.append((name, f.get("name") or name, f.get("type") or "string", bool(f.get("required"))))
    decls = "\n".join(f"  final {DART_TYPES.get(t, 'String')}{'' if r else '?'} {n};" for n, _, t, r in fields)
    params = "\n".join(f"    {'required ' if r else ''}this.{n}," for n, _, t, r in fields)
    from_json = "\n".join(f"        {n}: {_from_json(t, f'json[{dart.string(k)}]', r)}," for n, k, t, r in fields)
    to_json = "\n".join(f"        {dart.string(k)}: {_to_json(t, n, r)}," for n, k, t, r in fields)
    ctor = f"  const {cls}({{\n{params}\n  }});" if fields else f"  const {cls}();"
    source = f"""// Generated by Wolf. Data model: {model.get('name')}
class {cls} {{
{ctor}

{decls}

  factory {cls}.fromJson(Map<String, dynamic> json) => {cls}(
{from_json}
      );

  Map<String, dynamic> toJson() => {{
{to_json}
      }};
}}
"""
    return cls, dart.snake(cls), source


def _table_name(cls: str) -> str:
    name = dart.snake(cls)
    return name if name.endswith("s") else name + "s"


def _backend_file(schema: dict, models: list[tuple[str, str]]) -> tuple[str | None, list[str]]:
    """Returns (source of lib/data/backend.dart or None, extra packages)."""
    backend = schema.get("backend") or {}
    provider = backend.get("provider", "none")
    imports = "\n".join(f"import '../models/{stem}.dart';" for _, stem in models)
    if provider == "supabase":
        methods = "\n\n".join(
            f"  Future<List<{cls}>> {dart.camel(_table_name(cls))}() async {{\n"
            f"    final rows = await Supabase.instance.client.from({dart.string(_table_name(cls))}).select();\n"
            f"    return rows.map({cls}.fromJson).toList();\n  }}"
            for cls, _ in models
        )
        return f"""// Generated by Wolf. Supabase connection.
import 'package:supabase_flutter/supabase_flutter.dart';
{imports}

const supabaseUrl = {dart.string(backend.get('url', ''))};
const supabaseAnonKey = {dart.string(backend.get('anonKey', ''))};

Future<void> initBackend() async {{
  if (supabaseUrl.isEmpty || supabaseAnonKey.isEmpty) return;
  await Supabase.initialize(url: supabaseUrl, anonKey: supabaseAnonKey);
}}

/// Reads data models from Supabase tables of the same (pluralized, snake_case) name.
class Repository {{
  const Repository();

{methods}
}}
""", ["supabase_flutter"]
    if provider == "rest":
        methods = "\n\n".join(
            f"  Future<List<{cls}>> {dart.camel(_table_name(cls))}() async {{\n"
            f"    final res = await http.get(Uri.parse('$baseUrl/{_table_name(cls)}'));\n"
            f"    final rows = (jsonDecode(res.body) as List).cast<Map<String, dynamic>>();\n"
            f"    return rows.map({cls}.fromJson).toList();\n  }}"
            for cls, _ in models
        )
        return f"""// Generated by Wolf. REST API connection.
import 'dart:convert';

import 'package:http/http.dart' as http;
{imports}

const baseUrl = {dart.string((backend.get('url') or '').rstrip('/'))};

Future<void> initBackend() async {{}}

/// Reads data models from `GET <baseUrl>/<model>s`.
class Repository {{
  const Repository();

{methods}
}}
""", ["http"]
    if provider == "firebase":
        methods = "\n\n".join(
            f"  Future<List<{cls}>> {dart.camel(_table_name(cls))}() async {{\n"
            f"    final snap = await FirebaseFirestore.instance.collection({dart.string(_table_name(cls))}).get();\n"
            f"    return snap.docs.map((d) => {cls}.fromJson({{...d.data(), 'id': d.id}})).toList();\n  }}"
            for cls, _ in models
        )
        return f"""// Generated by Wolf. Firebase connection.
// Run `flutterfire configure` to add your platform config files before building.
import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/foundation.dart';
{imports}

Future<void> initBackend() async {{
  try {{
    await Firebase.initializeApp();
  }} catch (e) {{
    debugPrint('Firebase is not configured yet: $e');
  }}
}}

/// Reads data models from Firestore collections of the same (pluralized, snake_case) name.
class Repository {{
  const Repository();

{methods}
}}
""", ["firebase_core", "cloud_firestore"]
    return None, []


# ─── Entry point ─────────────────────────────────────────────────────────────


def _main_file(schema: dict, screens: list[ScreenInfo], has_backend: bool) -> str:
    nav = schema.get("navigation") or {}
    by_id = {s.id: s for s in screens}
    tabs = [t for t in nav.get("tabs") or [] if t.get("screenId") in by_id]
    use_tabs = nav.get("type") == "tabs" and len(tabs) >= 2
    initial = by_id.get(nav.get("initialScreenId")) or (screens[0] if screens else None)

    imports = ["import 'package:flutter/material.dart';", ""]
    if has_backend:
        imports.append("import 'data/backend.dart';")
    imports += [f"import 'screens/{s.file_name}.dart';" for s in screens]
    imports.append("import 'theme.dart';")

    routes = "\n".join(f"        {s.class_name}.routeName: (context) => const {s.class_name}()," for s in screens)
    title = dart.string((schema.get("build") or {}).get("appName") or schema.get("name") or "Wolf App")
    if use_tabs:
        start = f"      home: const AppShell(),"
    elif initial:
        start = f"      initialRoute: {initial.class_name}.routeName,"
    else:
        start = "      home: const Scaffold(body: Center(child: Text('No screens yet'))),"

    main_fn = (
        "Future<void> main() async {\n  WidgetsFlutterBinding.ensureInitialized();\n  await initBackend();\n  runApp(const WolfApp());\n}"
        if has_backend else
        "void main() {\n  runApp(const WolfApp());\n}"
    )
    source = f"""// Generated by Wolf.
{chr(10).join(imports)}

{main_fn}

class WolfApp extends StatelessWidget {{
  const WolfApp({{super.key}});

  @override
  Widget build(BuildContext context) {{
    return MaterialApp(
      title: {title},
      debugShowCheckedModeBanner: false,
      theme: buildTheme(),
{start}
      routes: {{
{routes}
      }},
    );
  }}
}}
"""
    if use_tabs:
        tab_screens = [by_id[t["screenId"]] for t in tabs]
        initial_index = next((i for i, s in enumerate(tab_screens) if initial and s.id == initial.id), 0)
        destinations = "\n".join(
            f"          NavigationDestination(icon: Icon({dart.icon(t.get('icon'))}), label: {dart.string(t.get('label') or by_id[t['screenId']].name)}),"
            for t in tabs
        )
        children = "\n".join(f"    {s.class_name}()," for s in tab_screens)
        source += f"""
/// Bottom navigation between the app's top-level tabs.
class AppShell extends StatefulWidget {{
  const AppShell({{super.key}});

  @override
  State<AppShell> createState() => _AppShellState();
}}

class _AppShellState extends State<AppShell> {{
  int _index = {initial_index};

  static const _tabs = <Widget>[
{children}
  ];

  @override
  Widget build(BuildContext context) {{
    return Scaffold(
      body: IndexedStack(index: _index, children: _tabs),
      bottomNavigationBar: NavigationBar(
        selectedIndex: _index,
        onDestinationSelected: (index) => setState(() => _index = index),
        destinations: const [
{destinations}
        ],
      ),
    );
  }}
}}
"""
    return source


def _pubspec(schema: dict, packages: list[str]) -> str:
    b = schema.get("build") or {}
    version = str(b.get("version") or "1.0.0")
    if not re.match(r"^\d+\.\d+\.\d+$", version):
        version = "1.0.0"
    build_number = b.get("buildNumber") if isinstance(b.get("buildNumber"), int) else 1
    description = (schema.get("description") or "A Flutter app built with Wolf.").replace("\n", " ").replace('"', "'")[:180]
    deps = "\n".join(f"  {p}: {PACKAGES[p]}" for p in sorted(set(packages)))
    return f"""name: {_package_name(schema)}
description: "{description}"
publish_to: "none"
version: {version}+{build_number}

environment:
  sdk: ">=3.4.0 <4.0.0"

dependencies:
  flutter:
    sdk: flutter
{deps}

dev_dependencies:
  flutter_test:
    sdk: flutter
  flutter_lints: ^5.0.0

flutter:
  uses-material-design: true
"""


def _readme(schema: dict, platforms: list[str]) -> str:
    name = schema.get("name") or "Wolf App"
    plats = ",".join(p for p in (platforms or ["android", "ios"]) if p in ("android", "ios")) or "android,ios"
    return f"""# {name}

{schema.get('description') or ''}

Generated by [Wolf](https://github.com/Odinachi/Wolf).

## Run it

```bash
flutter create . --platforms={plats}   # adds the platform folders
flutter pub get
flutter run
```
"""


def generate_project(schema: dict[str, Any]) -> GeneratedProject:
    """Compiles a Wolf app schema (as a JSON-like dict) into a map of file path -> contents."""
    screens = _screens(schema)
    ctx = Context(routes={s.id: s.route for s in screens})
    files: dict[str, str] = {}

    screen_by_id = {s.get("id"): s for s in schema.get("screens") or []}
    for info in screens:
        source, _ = _screen_file(screen_by_id[info.id], info, ctx)
        files[f"lib/screens/{info.file_name}.dart"] = source

    models = []
    used_stems: set[str] = set()
    for model in schema.get("dataModels") or []:
        cls, stem, source = _model_file(model)
        if stem in used_stems:
            ctx.warnings.append(f"Skipped duplicate data model '{model.get('name')}'.")
            continue
        used_stems.add(stem)
        models.append((cls, stem))
        files[f"lib/models/{stem}.dart"] = source

    backend_source, backend_packages = _backend_file(schema, models)
    if backend_source:
        files["lib/data/backend.dart"] = backend_source

    packages = ["google_fonts", *backend_packages]
    if ctx.uses_url_launcher:
        packages.append("url_launcher")

    files["lib/main.dart"] = _main_file(schema, screens, backend_source is not None)
    files["lib/theme.dart"] = _theme_file(schema)
    files["lib/widgets.dart"] = WIDGETS_DART
    files["pubspec.yaml"] = _pubspec(schema, packages)
    files["analysis_options.yaml"] = "include: package:flutter_lints/flutter.yaml\n"
    # Shipped so `flutter create .` doesn't add its counter-app test, which references a missing MyApp.
    files["test/widget_test.dart"] = SMOKE_TEST.replace("PACKAGE", _package_name(schema))
    files["README.md"] = _readme(schema, (schema.get("build") or {}).get("platforms") or [])
    return GeneratedProject(files=dict(sorted(files.items())), warnings=ctx.warnings)
