def _theme_file(schema: dict) -> str:
    t = schema.get("theme") or {}
    primary = dart.color(t.get("primary")) or "Color(0xFF6750A4)"
    brightness = "Brightness.dark" if t.get("brightness") == "dark" else "Brightness.light"
    radius = dart.number(t.get("radius")) or "12.0"
    overrides = [
        named("primary", dart.color(t.get("primary"))),
        named("secondary", dart.color(t.get("secondary"))),
        named("surface", dart.color(t.get("surface"))),
        named("onSurface", dart.color(t.get("text"))),
        named("onSurfaceVariant", dart.color(t.get("mutedText"))),
    ]
    scheme = f"ColorScheme.fromSeed(seedColor: {primary}, brightness: {brightness})"
    if any(overrides):
        joined = dart.indent(",\n".join(o for o in overrides if o), 4)
        scheme = f"{scheme}.copyWith(\n{joined},\n  )"
    font = dart.string(t.get("fontFamily") or "Inter")
    return f"""// Generated by Wolf. The app theme.
import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

const double kRadius = {radius};

ThemeData buildTheme() {{
  final scheme = {scheme};
  final base = ThemeData(
    useMaterial3: true,
    colorScheme: scheme,
    scaffoldBackgroundColor: {dart.color(t.get("background")) or "scheme.surface"},
    filledButtonTheme: FilledButtonThemeData(
      style: FilledButton.styleFrom(
        minimumSize: const Size(0, 48),
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(kRadius)),
      ),
    ),
    outlinedButtonTheme: OutlinedButtonThemeData(
      style: OutlinedButton.styleFrom(
        minimumSize: const Size(0, 48),
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(kRadius)),
      ),
    ),
    inputDecorationTheme: InputDecorationTheme(
      border: OutlineInputBorder(borderRadius: BorderRadius.circular(kRadius)),
    ),
  );
  TextTheme textTheme;
  try {{
    textTheme = GoogleFonts.getTextTheme({font}, base.textTheme);
  }} catch (_) {{
    textTheme = base.textTheme; // Unknown Google Font: keep the default.
  }}
  return base.copyWith(textTheme: textTheme);
}}
"""


