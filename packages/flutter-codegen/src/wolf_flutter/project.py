def _screen_file(screen: dict, info: ScreenInfo, ctx: Context) -> tuple[str, bool]:
    """Returns the Dart source and whether it uses url_launcher."""
    before = ctx.uses_url_launcher
    ctx.uses_url_launcher = False
    root = screen.get("root") or {}
    root_style = root.get("style") or {}
    children = [c for c in root.get("children") or [] if isinstance(c, dict)]

    app_bar = None
    if children and children[0].get("type") == "AppBar":
        bar = children.pop(0)
        props = bar.get("props") or {}
        style = bar.get("style") or {}
        actions = None
        if props.get("actionIcon"):
            actions = widget_list([call("IconButton", ["onPressed: () {}", f"icon: Icon({dart.icon(props['actionIcon'])})"])])
        app_bar = call("AppBar", [
            named("title", f"Text({dart.string(props.get('title', ''))})"),
            None if props.get("showBack") else "automaticallyImplyLeading: false",
            named("backgroundColor", dart.color(style.get("backgroundColor"))),
            named("foregroundColor", dart.color(style.get("color"))),
            named("actions", actions),
        ])

    # A flexible Spacer or an expanded child needs a bounded Column, so those screens don't scroll.
    needs_flex = any(
        (c.get("type") == "Spacer" and not (c.get("style") or {}).get("height")) or (c.get("style") or {}).get("expand")
        for c in children
    )
    compiled = with_gap([compile_node(c, ctx, "vertical") for c in children], root_style.get("gap"), "vertical")
    column = call("Column", [
        "crossAxisAlignment: CrossAxisAlignment.stretch",
        named("mainAxisAlignment", {"center": "MainAxisAlignment.center", "end": "MainAxisAlignment.end", "spaceBetween": "MainAxisAlignment.spaceBetween"}.get(root_style.get("mainAxisAlignment"))),
        named("children", widget_list(compiled)),
    ])
    padding = dart.edge_insets(root_style.get("padding"))
    if needs_flex:
        body = call("SafeArea", [named("child", call("Padding", [named("padding", padding), named("child", column)]) if padding else column)])
    else:
        body = call("SafeArea", [named("child", call("SingleChildScrollView", [named("padding", padding), named("child", column)]))])

    scaffold = call("Scaffold", [
        named("backgroundColor", dart.color(screen.get("backgroundColor") or root_style.get("backgroundColor"))),
        named("appBar", app_bar),
        named("body", body),
    ])

    uses_url = ctx.uses_url_launcher
    ctx.uses_url_launcher = before or uses_url
    imports = ["import 'package:flutter/material.dart';"]
    if uses_url:
        imports.append("import 'package:url_launcher/url_launcher.dart';")
    if any(w in scaffold for w in ("WolfSwitch(", "WolfCheckbox(", "WolfSlider(")):
        imports.append("")
        imports.append("import '../widgets.dart';")

    source = f"""// Generated by Wolf. Screen: {info.name}
{chr(10).join(imports)}

class {info.class_name} extends StatelessWidget {{
  const {info.class_name}({{super.key}});

  static const routeName = {dart.string(info.route)};

  @override
  Widget build(BuildContext context) {{
    return {dart.indent(scaffold, 4).lstrip()};
  }}
}}
"""
    return source, uses_url


